import { createRequire } from "node:module";
import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createServer } from "node:net";

const require = createRequire(resolve("frontend/package.json"));
const { chromium, expect } = require("@playwright/test");
const root = resolve(".cache/p6-browser", String(Date.now()));
await mkdir(root, { recursive: true });
const port = await new Promise((done, fail) => {
    const server = createServer(); server.once("error", fail);
    server.listen(0, "127.0.0.1", () => { const value = server.address().port; server.close(() => done(value)); });
});
const executable = process.env.REPOWATCH_P6_PYTHON ?? resolve("backend/.venv/Scripts/python.exe");
const host = spawn(executable, ["-X", "utf8", "experiments/p6_browser_host.py", "--data-dir", resolve(root, "data"), "--port", String(port)], { windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
let browser, stderr = "";
host.stderr.on("data", chunk => { stderr = (stderr + chunk.toString()).slice(-4000); });
const passed = [];
try {
    const setup = await new Promise((done, fail) => {
        let output = ""; const timer = setTimeout(() => fail(new Error(stderr || "host timeout")), 30000);
        host.once("exit", () => { clearTimeout(timer); fail(new Error(stderr || "host exited")); });
        host.stdout.on("data", chunk => { output += chunk.toString(); if (output.includes("\n")) { clearTimeout(timer); done(JSON.parse(output.split("\n")[0])); } });
    });
    browser = await chromium.launch({ channel: "msedge", headless: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
    let page = await context.newPage();
    const errors = []; context.on("page", value => value.on("pageerror", error => errors.push(error.message)));
    await page.goto(`http://127.0.0.1:${port}/#session=${setup.bootstrap}`);
    await page.getByRole("button", { name: "系统与维护", exact: true }).click();
    await expect(page.getByRole("heading", { name: "系统与维护", exact: true })).toBeVisible();
    await expect(page.getByText(/0027_local_operations/)).toBeVisible();
    passed.push("production static system view");
    await page.getByLabel("完成任务产物保留天数").fill("40");
    await page.getByRole("button", { name: "保存保留策略", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("保留策略已保存");
    await page.reload();
    await page.getByRole("button", { name: "系统与维护", exact: true }).click();
    await expect(page.getByLabel("完成任务产物保留天数")).toHaveValue("40");
    passed.push("retention revision survives reload");
    await page.getByRole("button", { name: "创建一致备份", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("一致备份已完成并核验");
    await expect(page.locator("li").filter({ hasText: "backup-" })).toHaveCount(1);
    passed.push("verified backup and persisted list");
    await page.getByRole("button", { name: "预览安全清理", exact: true }).click();
    await expect(page.getByText("候选 1 项，受保护 1 项。", { exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "执行安全清理", exact: true })).toBeDisabled();
    await page.getByLabel("我已核对候选，确认清理符合当前保留策略的完成任务内容").check();
    await page.getByRole("button", { name: "执行安全清理", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("安全清理已完成");
    const artifacts = await page.evaluate(async () => {
        const state = await (await fetch("/api/v1/state")).json();
        const details = await Promise.all(state.tasks.map(async task => (await (await fetch(`/api/v1/tasks/${task.id}`)).json())));
        return details.flatMap(task => task.artifacts);
    });
    if (!artifacts.find(item => item.id === "active")?.available || artifacts.find(item => item.id === "finished")?.available) throw new Error("retention reference mismatch");
    passed.push("preview confirmation and active evidence protection");
    await page.getByText("依赖与支持边界", { exact: true }).click();
    await page.getByRole("button", { name: "显式开启原生执行配置", exact: true }).click();
    await expect(page.getByText("原生执行配置：已显式开启，但能力尚未准入，仍拒绝执行", { exact: true })).toBeVisible();
    passed.push("native explicit configuration retains capability refusal");
    const capabilityRoute = /\/api\/v1\/operations$/;
    await page.route(capabilityRoute, async route => {
        const response = await route.fetch();
        const body = await response.json();
        body.native_capability = { supported: true, reason: "UI-only live-admission state fixture" };
        await route.fulfill({ response, json: body });
    });
    await page.getByRole("button", { name: "刷新系统状态", exact: true }).click();
    await expect(page.getByText("原生执行配置：已显式开启，当前宿主能力核验通过", { exact: true })).toBeVisible();
    await page.unroute(capabilityRoute);
    await page.getByRole("button", { name: "刷新系统状态", exact: true }).click();
    await expect(page.getByText("原生执行配置：已显式开启，但能力尚未准入，仍拒绝执行", { exact: true })).toBeVisible();
    passed.push("native admission display follows API state fixture and reverts after live refresh");
    await page.getByRole("button", { name: "生成恢复核对报告", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("只读恢复核对报告已保存");
    await expect(page.getByRole("button", { name: "确认当前恢复核对", exact: true })).toBeDisabled();
    passed.push("restore report requires explicit user evidence");
    await page.getByLabel("恢复核对依据").fill("已核对临时夹具远端及凭据，工作区保持无效待重建");
    await page.getByRole("button", { name: "确认当前恢复核对", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("恢复核对已确认");
    await expect(page.getByRole("button", { name: "生成恢复核对报告", exact: true })).toBeDisabled();
    passed.push("restore confirmation persists without resuming queue");
    const before = await page.evaluate(async () => (await (await fetch("/api/v1/state")).json()));
    await page.close();
    await new Promise(done => setTimeout(done, 1500));
    page = await context.newPage();
    await page.goto(`http://127.0.0.1:${port}/`);
    await page.getByRole("button", { name: "系统与维护", exact: true }).click();
    await expect(page.getByRole("heading", { name: "系统与维护", exact: true })).toBeVisible();
    const after = await page.evaluate(async () => (await (await fetch("/api/v1/state")).json()));
    if (before.tasks.length !== after.tasks.length || after.control.paused !== 1 || after.tasks.some(task => task.budget.used.model_calls !== 0)) throw new Error("browser lifecycle changed execution");
    passed.push("browser close preserves services pause and zero model calls");
    await page.screenshot({ path: resolve(root, "system.png"), fullPage: true });
    if (errors.length) throw new Error(JSON.stringify(errors));
    await writeFile(resolve(root, "report.json"), JSON.stringify({ passed, errors, count: passed.length, installedWheel: Boolean(process.env.REPOWATCH_P6_PYTHON), externalModels: false, githubWrites: false }, null, 2));
    console.log(JSON.stringify({ passed: passed.length, report: resolve(root, "report.json") }));
} finally {
    await browser?.close();
    host.kill();
}
