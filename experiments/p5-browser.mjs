import { createRequire } from "node:module";
import { repositoryPage, settingsPage } from "./workbench-browser-navigation.mjs";
import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createServer } from "node:net";

const require = createRequire(resolve("frontend/package.json"));
const { chromium, expect } = require("@playwright/test");
const root = resolve(".cache/p5-browser", String(Date.now()));
await mkdir(root, { recursive: true });
const port = await new Promise((done, fail) => {
    const server = createServer(); server.once("error", fail);
    server.listen(0, "127.0.0.1", () => { const value = server.address().port; server.close(() => done(value)); });
});
const host = spawn(resolve("backend/.venv/Scripts/python.exe"), ["-X", "utf8", "experiments/p5_browser_host.py", "--data-dir", resolve(root, "data"), "--port", String(port)], { windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
let browser, stderr = "";
host.stderr.on("data", chunk => { stderr = (stderr + chunk.toString()).slice(-4000); });
try {
    const setup = await new Promise((done, fail) => {
        let output = ""; const timer = setTimeout(() => fail(new Error(stderr)), 30000);
        host.once("exit", () => { clearTimeout(timer); fail(new Error(stderr)); });
        host.stdout.on("data", chunk => { output += chunk.toString(); if (output.includes("\n")) { clearTimeout(timer); done(JSON.parse(output.split("\n")[0])); } });
    });
    browser = await chromium.launch({ channel: "msedge", headless: true });
    const page = await browser.newPage({ viewport: { width: 1500, height: 1100 } });
    const errors = []; page.on("pageerror", error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${port}/#session=${setup.bootstrap}`);
    const openMemory = async () => {
        await repositoryPage(page, "P5-browser-source", "配置");
        await page.getByRole("button", { name: "查看与管理记忆", exact: true }).click();
    };
    await openMemory();
    await expect(page.getByText("会话令牌刷新失败", { exact: true })).toBeVisible();
    const selected = () => page.evaluate(async id => (await (await fetch(`/api/v1/memories/${id}`)).json()), "p5-browser-memory");
    const search = async repository => page.evaluate(async repository => (await (await fetch(`/api/v1/memories/search?repository_id=${repository}&query=${encodeURIComponent("令牌")}`)).json()), repository);
    await settingsPage(page, "记忆索引");
    await page.getByRole("button", { name: "重建记忆索引", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("索引重建结果已回读");
    await openMemory();
    await page.getByLabel("检索经验").fill("令牌");
    await page.getByRole("button", { name: "检索记忆", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("检索完成");
    await page.getByRole("button", { name: "查看与纠正", exact: true }).click();
    await page.getByText("来源与代码版本", { exact: true }).click();
    await expect(page.locator("details").filter({has:page.getByText("来源与代码版本", {exact:true})}).locator("pre")).toBeVisible();
    await page.getByLabel("我已审阅待共享正文，确认不含原始上下文或敏感信息").check();
    await page.getByRole("button", { name: "保存去敏共享版本", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("记忆操作已保存");
    await settingsPage(page, "记忆索引");
    await page.getByRole("button", { name: "重建记忆索引", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("索引重建结果已回读");
    const shared = await search(setup.other_id);
    if (shared.items[0]?.visibility !== "shared" || shared.items[0]?.source.candidate_sha) throw new Error("cross repository boundary");
    await openMemory();
    await page.getByRole("button", { name: "查看与纠正", exact: true }).click();
    await page.getByRole("button", { name: "禁用记忆", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("记忆操作已保存并回读");
    await expect.poll(async () => (await selected()).enabled).toBe(0);
    if ((await search(setup.other_id)).items.length) throw new Error("disabled memory leaked");
    await page.getByRole("button", { name: "启用记忆", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("记忆操作已保存并回读");
    await expect.poll(async () => (await selected()).enabled).toBe(1);
    await page.getByLabel("方法", {exact:true}).fill("人工纠正后的方法，需要重新验证");
    await page.getByRole("button", { name: "保存正文", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("记忆操作已保存并回读");
    await expect.poll(async () => (await selected()).state).toBe("manual_unverified");
    await expect(page.getByText("检索结果与降级状态", {exact:true})).toHaveCount(0);
    if ((await search(setup.repository_id)).items.length) throw new Error("semantic edit inherited validation");
    await page.screenshot({path:resolve(root,"memory-management.png"),fullPage:true});
    await page.getByRole("button", { name: "删除记忆", exact: true }).click();
    await expect.poll(async () => (await selected()).deleted).toBe(1);
    await page.reload();
    await openMemory();
    await expect(page.getByText("已删除 · 修订 6", {exact:true})).toBeVisible();
    await page.getByRole("button", { name: "新增人工记录", exact:true }).click();
    for (const label of ["问题特征", "适用条件", "方法", "验证方式", "限制与未证实假设"]) await page.getByLabel(label,{exact:true}).fill("人工待验证记录");
    await page.getByRole("button", { name:"保存正文",exact:true}).click();
    await expect(page.getByRole("status")).toContainText("人工未验证记录已保存");
    await settingsPage(page, "记忆索引");
    await page.getByLabel("本地语义编码模型").selectOption("BAAI/bge-small-zh-v1.5");
    await page.getByRole("button", { name:"保存索引配置",exact:true}).click();
    await expect(page.getByRole("status")).toContainText("索引配置已保存");
    await page.getByRole("button", { name:"重建记忆索引",exact:true}).click();
    await expect(page.getByRole("status")).toContainText("索引重建结果已回读");
    await openMemory();
    await page.getByRole("button", { name:"查看复用审计",exact:true}).click();
    await expect(page.getByText("请求依赖核验与留存范围", {exact:true})).toBeVisible();
    const state = await page.evaluate(async () => (await (await fetch("/api/v1/state")).json()));
    if (!state.control.paused || state.tasks.length || errors.length) throw new Error(JSON.stringify({state,errors}));
    await page.screenshot({path:resolve(root,"index-and-retention.png"),fullPage:true});
    const checks = ["记忆查看与来源", "中文短词检索", "去敏共享范围", "禁用与启用", "语义纠正失去验证标签", "删除与刷新持久化", "人工记录", "索引配置与缺模型降级", "审计留存说明", "全局暂停下无隐式执行"];
    await writeFile(resolve(root,"report.json"), JSON.stringify({passed:checks.length,checks,errors,paused:state.control.paused},null,2));
    console.log(JSON.stringify({report:resolve(root,"report.json"),passed:checks.length}));
} finally { await browser?.close(); host.kill(); }
